-- ============================================================
-- 026: ФИО сотрудника — не длиннее 50 символов.
--
--   Поле в формах ограничено 50 символами (maxlength), сервер тоже
--   проверяет длину; здесь фиксируем то же ограничение на уровне БД.
--   Длинные значения (из ранних версий) аккуратно обрезаем, чтобы
--   alter не упал.
--
-- Идемпотентно.
-- ============================================================

update users set full_name = left(btrim(full_name), 50) where length(btrim(full_name)) > 50;

alter table users alter column full_name type varchar(50);
