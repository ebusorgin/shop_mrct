-- ============================================================
-- 010 — «Лавровый лист» из штук в граммы.
-- Позиция заведена в «шт», а приходит фасовкой: «лист лавровый 15 грамм, 1 шт» —
-- это 15 г содержимого. Импорт документов теперь считает такие строки в граммах,
-- и приход упирается в «Нельзя перевести «count» в «mass»», пока у товара штуки.
-- Числа оставляем как есть (демо-остаток 200 шт -> 200 г, avg_cost = 0 — деньги не
-- двигаются, списаний и накладных по позиции нет), меняем только единицу: товар,
-- позиции техкарт, формулировку движения склада.
-- Идемпотентно: после первого прохода единица уже «г» и условия больше не совпадают.
-- ============================================================

-- 1) сама позиция
update products
   set unit_id = (select id from units where code = 'г')
 where name = 'Лавровый лист'
   and unit_id = (select id from units where code = 'шт');

-- 2) сырьё в техкартах (количество на порцию численно остаётся как было)
update tech_card_items i
   set unit_id = (select id from units where code = 'г')
  from products p
 where i.source_type = 'raw'
   and i.ref_id = p.id
   and p.name = 'Лавровый лист'
   and i.unit_id = (select id from units where code = 'шт');

-- 3) чтобы журнал не врал: в комментарии движения тоже меняем единицу
update movements m
   set comment = replace(m.comment, 'шт', 'г')
  from products p
 where m.product_id = p.id
   and p.name = 'Лавровый лист'
   and m.comment like '%шт';
