-- ============================================================
-- 013 — Срок годности номенклатуры.
--   shelf_life_days — целое число дней; NULL = срок не задан
--   (обратная совместимость: у существующих позиций пусто).
-- Хранится как справочный атрибут товара (сколько дней он годен),
-- а не как конкретная дата — дата списания выводится из даты прихода.
-- Идемпотентно.
-- ============================================================

alter table products add column if not exists shelf_life_days integer check (shelf_life_days is null or shelf_life_days >= 0);
