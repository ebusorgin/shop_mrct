-- ============================================================
-- 025: Магазинные пользователи.
--
--   users.store_id — точка продаж, к которой привязан сотрудник.
--     null     — офис / администратор (доступ ко всей CRM);
--     not null — магазинный пользователь: при входе открывается
--                страница только своей точки (store_id один, поэтому
--                привязаться к двум магазинам нельзя).
--   У одного магазина может быть сколько угодно пользователей —
--   ограничения «один пользователь на точку» нет.
--
-- Идемпотентно.
-- ============================================================

alter table users add column if not exists store_id int references stores(id) on delete set null;

-- выборка «кто из сотрудников привязан к точке»
create index if not exists users_store_idx on users (store_id);

-- магазинный пользователь не администратор: иначе непонятно, какую
-- страницу открывать после входа (см. routes/auth.ts — там это правило же).
update users set is_admin = false where store_id is not null and is_admin;
