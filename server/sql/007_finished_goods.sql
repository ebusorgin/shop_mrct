-- 2.1 базовые входы (один base на заготовку, с уварком/выходом)
insert into semi_inputs (semi_id, source_type, ref_id, role, yield_pct)
select sp.id, 'raw', p.id, 'base', v.yld
  from (values
    ('Морковь варёная',  'Морковь',        80),
    ('Яйцо варёное',     'Яйцо куриное',   100),
    ('Курица варёная',   'Куриное филе',   70),
    ('Рис отварной',     'Рис',            100)
  ) as v(semi, inp, yld)
  join semi_products sp on sp.name = v.semi
  join products p on p.name = v.inp
 where not exists (select 1 from semi_inputs si where si.semi_id = sp.id and si.role = 'base');

-- картофельное пюре: база — другой полуфабрикат (Картофель варёный)
insert into semi_inputs (semi_id, source_type, ref_id, role, yield_pct)
select sp.id, 'semi', s2.id, 'base', 100
  from semi_products sp
  join semi_products s2 on s2.name = 'Картофель варёный'
 where sp.name = 'Картофельное пюре'
   and not exists (select 1 from semi_inputs si where si.semi_id = sp.id and si.role = 'base');

-- 2.2 добавки (расход баз. единиц на 1 баз. единицу выхода)
insert into semi_inputs (semi_id, source_type, ref_id, role, qty_per_output)
select sp.id, i.src, coalesce(p.id, s2.id), 'additive', i.qpo
  from (values
    ('Рис отварной',       'raw',  'Вода',              2.0),
    ('Картофельное пюре',  'raw',  'Молоко',            0.15),
    ('Картофельное пюре',  'raw',  'Масло сливочное',   0.05)
  ) as i(semi, src, inp, qpo)
  join semi_products sp on sp.name = i.semi
  left join products p on i.src = 'raw'  and p.name = i.inp
  left join semi_products s2 on i.src = 'semi' and s2.name = i.inp
 where coalesce(p.id, s2.id) is not null
   and not exists (select 1 from semi_inputs si where si.semi_id = sp.id and si.role = 'additive' and si.ref_id = coalesce(p.id, s2.id));

